/**
 * The one set of named glyphs (§10.4: *"One icon set: lucide"*).
 *
 * ## Why a closed map and not a string
 *
 * `UiCommand.icon` was declared `string`, *"an icon name from the generated
 * set"*, and no generated set existed, so every icon a command could name was
 * a string nothing resolved. Such a name renders nothing and fails no check,
 * which is the display-only defect on the smallest scale. Keying commands
 * by {@link IconName} makes a misspelt glyph a compile error (B5).
 *
 * ## One import site
 *
 * Every named glyph a surface draws comes through this map, so *which icons does
 * the application use* has one answer, and the bundle carries only these. A
 * glyph imported ad hoc beside it would be a second answer. `IconButton` still
 * takes a `LucideIcon`, which is the component from this map.
 *
 * Names were checked against `lucide-react` 1.34.0's own declarations on
 * 2026-09-14, and `FormInput`, `FilePlus2`, `FileJson` and `FileCode2` are
 * absent from that release. The compiler holds the rest.
 */
