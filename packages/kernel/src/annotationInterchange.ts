/**
 * Every exchangeable annotation in the document, in page order and each page's walk order.
 *
 * An annotation whose entries do not make a record — a subtype outside the set, a highlight with
 * no quadrilaterals — is left out rather than written half-described.
 */
export function readInterchangeAnnotations(session: MupdfSession): Promise<readonly InterchangeAnnotation[]> {
  return withDocument(session, (document) => {
    const found: InterchangeAnnotation[] = [];
    const pages = document.countPages();
    for (let page = 0; page < pages; page += 1) {
      for (const annotation of document.loadPage(page).getAnnotations()) {
        const record = tolerantRecord(candidateFrom(annotation.getObject(), page));
        if (record !== null) found.push(record);
      }
    }
    return found;
  });
}

/**
 * One annotation dictionary's entries as a candidate record, unchecked.
 *
 * THE ONE READER OF ENTRIES, taken by the document walk and by an FDF's `/Annots` alike, so a
 * file and a document cannot disagree about what `/C` means (B3a). What differs is what each does
 * with a candidate the schema refuses: {@link tolerantRecord} for the document, a refusal for a file.
 */
function candidateFrom(dictionary: PDFObject, page: number): Candidate {
  const subtype = nameIn(dictionary.get('Subtype'));
  const rect = numbersIn(dictionary.get('Rect'));
  // CHECKED BEFORE THE SECOND `get`: an absent `/BS` reads as MuPDF's shared null, which belongs to
  // no document and throws when asked for a key.
  const style = dictionary.get('BS');
  const border = (style.isDictionary() ? numberIn(style.get('W')) : undefined) ?? numbersIn(dictionary.get('Border'))?.[2];
  const endings = namesIn(dictionary.get('LE'));
  const ink = dictionary.get('InkList');
  const strokes: number[][] = [];
  if (ink.isArray()) {
    for (let index = 0; index < ink.length; index += 1) {
      const stroke = numbersIn(ink.get(index));
      if (stroke !== undefined) strokes.push(stroke);
    }
  }
  return present({
    page,
    subtype,
    rect,
    colour: numbersIn(dictionary.get('C')),
    interiorColour: numbersIn(dictionary.get('IC')),
    opacity: numberIn(dictionary.get('CA')),
    borderWidth: border,
    contents: textIn(dictionary.get('Contents')),
    author: textIn(dictionary.get('T')),
    subject: textIn(dictionary.get('Subj')),
    modified: textIn(dictionary.get('M')),
    quadPoints: numbersIn(dictionary.get('QuadPoints')),
    inkList: strokes.length > 0 ? strokes : undefined,
    vertices: numbersIn(dictionary.get('Vertices')),
    line: numbersIn(dictionary.get('L')),
    lineEndings: endings?.length === 2 ? endings : undefined,
    icon: subtype === 'Text' ? nameIn(dictionary.get('Name')) : undefined,
    defaultAppearance: subtype === 'FreeText' ? textIn(dictionary.get('DA')) : undefined,
  });
}

/** A record before the schema has seen it: every entry of the record's, each of unknown shape. */
type Candidate = { -readonly [K in keyof InterchangeAnnotation]?: unknown };

/** The candidate's entries that are there — an absent entry is no key, as in the dictionary. */
function present(candidate: Candidate): Candidate {
  const kept: Candidate = {};
  for (const [key, value] of Object.entries(candidate)) {
    if (value !== undefined) Object.assign(kept, { [key]: value });
  }
  return kept;
}

/**
 * A document's own annotation as a record, or `null` where it is not one.
 *
 * AN ENTRY THE SCHEMA REFUSES IS DROPPED BEFORE THE RECORD IS: a document's own date in a format
 * the schema does not accept should not cost the annotation on export. Only the optional entries
 * are retried; a record still refused is not exchangeable.
 */
function tolerantRecord(candidate: Candidate): InterchangeAnnotation | null {
  const parsed = interchangeAnnotationSchema.safeParse(candidate);
  if (parsed.success) return parsed.data;
  const kept: Candidate = { page: candidate.page, subtype: candidate.subtype, rect: candidate.rect };
  for (const [key, value] of Object.entries(candidate)) {
    if (key in kept || value === undefined) continue;
    const trial = interchangeAnnotationSchema.safeParse({ ...kept, [key]: value });
    const issues = trial.success ? [] : trial.error.issues.filter((issue) => issue.path[0] === key);
    if (issues.length === 0) Object.assign(kept, { [key]: value });
  }
  const retried = interchangeAnnotationSchema.safeParse(kept);
  return retried.success ? retried.data : null;
}

/**
 * A PDF number as MuPDF holds it, at the precision it holds it: a real is a C `float`, so `0.2`
 * written and read back is `0.20000000298023224` (measured 2026-09-17). Seven significant digits
 * is what a `float` carries, so the value is given at that — `0.2` stays `0.2`, and a record read
 * from a document and from its own export agree.
 */
function engineNumber(value: PDFObject): number {
  return Number(Math.fround(value.asNumber()).toPrecision(7));
}

function numberIn(value: PDFObject): number | undefined {
  return value.isNumber() ? engineNumber(value) : undefined;
}

function numbersIn(value: PDFObject): number[] | undefined {
  if (!value.isArray()) return undefined;
  const out: number[] = [];
  for (let index = 0; index < value.length; index += 1) {
    const entry = value.get(index);
    if (!entry.isNumber()) return undefined;
    out.push(engineNumber(entry));
  }
  return out;
}

function namesIn(value: PDFObject): string[] | undefined {
  if (!value.isArray()) return undefined;
  const out: string[] = [];
  for (let index = 0; index < value.length; index += 1) {
    const entry = value.get(index);
    if (!entry.isName()) return undefined;
    out.push(entry.asName());
  }
  return out;
}

function nameIn(value: PDFObject): string | undefined {
  return value.isName() ? value.asName() : undefined;
}

function textIn(value: PDFObject): string | undefined {
  return value.isString() ? value.asString() : undefined;
}

