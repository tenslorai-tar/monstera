/**
 * Annotations to and from a file — D8's *annotation import / export*, in JSON, XFDF and FDF
 * ([ADR-0077](../../../docs/DECISIONS/0077-annotations-are-exchanged-as-dictionary-entries-in-user-space.md)).
 *
 * ## The record is the annotation's own dictionary entries, in PDF user space
 *
 * Not an authoring draft: a draft is a drag — a highlight's two ends, from which MuPDF finds the
 * text — so a highlight read back into one has already lost its quadrilaterals. And not MuPDF's
 * getters and setters, which answer in the displayed page frame: measured 2026-09-17, a square
 * whose `/Rect` is `[100 100 300 200]` reads back from `getRect` as `[101 593 299 691]`. The entries
 * themselves are in user space, which is the space XFDF and FDF carry, so they are read and written
 * with no transform between — and measured the same day, entries written raw render on an upright
 * and a rotated page alike (1,783 pixels of ink each), and a save writes the appearance stream from
 * them (for a red square of width 7: `7 w`, `1 0 0 RG` and the box inset by half the width).
 *
 * ## A closed set of entries, never a copied dictionary
 *
 * A dictionary from a stranger's file can carry an action, a JavaScript entry or an appearance
 * stream whose content this build would then draw (invariant 24). So the record names the entries
 * that describe an annotation — its box, colours, opacity, border, text, author, subject, date and
 * geometry — and each is checked by one schema whichever format it came from. The appearance is
 * regenerated by MuPDF from those entries.
 */

/** The subtypes exchanged: every markup this build can list, and nothing that carries a file or a sound. */
export const INTERCHANGE_SUBTYPES = [
  'Text',
  'FreeText',
  'Line',
  'Square',
  'Circle',
  'Polygon',
  'PolyLine',
  'Highlight',
  'Underline',
  'Squiggly',
  'StrikeOut',
  'Caret',
  'Ink',
  'Redact',
] as const;

export type InterchangeSubtype = (typeof INTERCHANGE_SUBTYPES)[number];

/** How many annotations one file carries. The XFDF reader's bound and this one are the same number. */
export const MAX_INTERCHANGE_ANNOTATIONS = 4096;

/** How many points one geometry list holds. */
export const MAX_INTERCHANGE_POINTS = 4096;

/** How long an annotation's text may be; an author, subject or date is bounded at 512. */
const MAX_INTERCHANGE_TEXT = 16_384;
const MAX_INTERCHANGE_LABEL = 512;

/** The line endings the format defines. */
const LINE_ENDINGS = [
  'None',
  'Square',
  'Circle',
  'Diamond',
  'OpenArrow',
  'ClosedArrow',
  'Butt',
  'ROpenArrow',
  'RClosedArrow',
  'Slash',
] as const;

/** The icons a `/Text` note may name (PDF 32000-1, 12.5.6.4). */
const NOTE_ICONS = ['Comment', 'Key', 'Note', 'Help', 'NewParagraph', 'Paragraph', 'Insert'] as const;

/**
 * A default appearance this build accepts: a font resource, a size and one colour operator —
 * what MuPDF writes. Anything longer is content-stream syntax from a stranger's file.
 */
const DEFAULT_APPEARANCE = /^\/[A-Za-z][A-Za-z0-9]{0,31} \d{1,3}(\.\d{1,4})? Tf( -?\d{0,3}(\.\d{1,6})?){1,4} (g|rg|k)$/u;

/** A PDF date as annotations carry one: `D:` and up to the format's fields. */
const PDF_DATE = /^D:\d{4}[0-9+\-Z']{0,19}$/u;

// FINITE BY zod 4's OWN RULE: `z.number()` refuses Infinity and NaN.
const coordinate = z.number().min(-1e7).max(1e7);
const colour = z
  .array(z.number().min(0).max(1))
  .refine((components) => [0, 1, 3, 4].includes(components.length), 'a colour has 0, 1, 3 or 4 components');
const points = z
  .array(coordinate)
  .max(MAX_INTERCHANGE_POINTS * 2)
  .refine((numbers) => numbers.length % 2 === 0, 'points come in pairs');

/** One exchanged annotation, checked the same way whichever format it came from. */
export const interchangeAnnotationSchema = z
  .object({
    /** Zero-based, as XFDF's own `page` attribute is. */
    page: z.number().int().nonnegative(),
    subtype: z.enum(INTERCHANGE_SUBTYPES),
    rect: z.tuple([coordinate, coordinate, coordinate, coordinate]),
    colour: colour.optional(),
    interiorColour: colour.optional(),
    opacity: z.number().min(0).max(1).optional(),
    borderWidth: z.number().min(0).max(1000).optional(),
    contents: z.string().max(MAX_INTERCHANGE_TEXT).optional(),
    author: z.string().max(MAX_INTERCHANGE_LABEL).optional(),
    subject: z.string().max(MAX_INTERCHANGE_LABEL).optional(),
    modified: z.string().max(64).regex(PDF_DATE).optional(),
    quadPoints: points.refine((numbers) => numbers.length % 8 === 0, 'quadrilaterals have eight numbers').optional(),
    inkList: z.array(points).min(1).max(256).optional(),
    vertices: points.optional(),
    line: z.tuple([coordinate, coordinate, coordinate, coordinate]).optional(),
    lineEndings: z.tuple([z.enum(LINE_ENDINGS), z.enum(LINE_ENDINGS)]).optional(),
    icon: z.enum(NOTE_ICONS).optional(),
    defaultAppearance: z.string().max(128).regex(DEFAULT_APPEARANCE).optional(),
  })
  .strict()
  .superRefine((record, context) => {
    // THE GEOMETRY A SUBTYPE IS DRAWN FROM is required, because without it MuPDF draws nothing
    // and the import would report an annotation a person cannot see.
    const needs: Partial<Record<InterchangeSubtype, keyof typeof record>> = {
      Highlight: 'quadPoints',
      Underline: 'quadPoints',
      Squiggly: 'quadPoints',
      StrikeOut: 'quadPoints',
      Ink: 'inkList',
      Polygon: 'vertices',
      PolyLine: 'vertices',
      Line: 'line',
    };
    const needed = needs[record.subtype];
    if (needed !== undefined && record[needed] === undefined) {
      context.addIssue({ code: 'custom', message: `a ${record.subtype} needs its ${needed}` });
    }
  });

export type InterchangeAnnotation = z.infer<typeof interchangeAnnotationSchema>;

