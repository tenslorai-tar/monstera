/**
 * What an annotation file says, whichever format it is in, every record checked by the one schema.
 *
 * A record the schema refuses refuses the file: the import is one command, and adding the
 * annotations that happened to be well-formed would leave the rest out with no report.
 */
export function parseAnnotationData(bytes: Uint8Array, format: AnnotationDataFormat): readonly InterchangeAnnotation[] {
  if (format === 'fdf') return parseFdf(bytes);
  let text: string;
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  } catch (error) {
    throw new UnreadableAnnotationDataError(error instanceof Error ? error.message : String(error));
  }
  const candidates = format === 'json' ? jsonCandidates(text) : readXfdfAnnotations(text).flatMap(xfdfCandidate);
  if (candidates.length > MAX_INTERCHANGE_ANNOTATIONS) {
    throw new UnreadableAnnotationDataError(`it carries more than ${String(MAX_INTERCHANGE_ANNOTATIONS)} annotations`);
  }
  return candidates.map((candidate, index) => checked(candidate, index));
}

function checked(candidate: unknown, index: number): InterchangeAnnotation {
  const parsed = interchangeAnnotationSchema.safeParse(candidate);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    throw new UnreadableAnnotationDataError(
      `annotation ${String(index + 1)} ${issue === undefined ? 'is malformed' : `— ${issue.path.join('.')}: ${issue.message}`}`,
    );
  }
  return parsed.data;
}

const jsonFileSchema = z
  .object({
    format: z.literal(ANNOTATION_DATA_JSON_MARKER),
    version: z.literal(ANNOTATION_DATA_JSON_VERSION),
    annotations: z.array(z.unknown()).max(MAX_INTERCHANGE_ANNOTATIONS),
  })
  .strict();

function jsonCandidates(text: string): readonly unknown[] {
  let decoded: unknown;
  try {
    decoded = JSON.parse(text);
  } catch (error) {
    throw new UnreadableAnnotationDataError(error instanceof Error ? error.message : String(error));
  }
  const parsed = jsonFileSchema.safeParse(decoded);
  if (!parsed.success) {
    throw new UnreadableAnnotationDataError("it is JSON, but not this build's annotation data");
  }
  return parsed.data.annotations;
}

const SUBTYPE_OF_ELEMENT = new Map<string, InterchangeSubtype>(
  INTERCHANGE_SUBTYPES.map((subtype) => [XFDF_ELEMENTS[subtype], subtype]),
);

/** Numbers in an attribute, separated by commas, semicolons or spaces; any other text refuses. */
function numbersOf(text: string, what: string): number[] {
  const parts = text.trim().split(/[\s,;]+/u).filter((part) => part !== '');
  return parts.map((part) => {
    const value = Number(part);
    if (!Number.isFinite(value)) throw new UnreadableAnnotationDataError(`${what} holds "${part.slice(0, 32)}", which is not a number`);
    return value;
  });
}

function colourOf(text: string): number[] {
  const match = /^#([0-9a-fA-F]{2})([0-9a-fA-F]{2})([0-9a-fA-F]{2})$/u.exec(text.trim());
  if (match === null) throw new UnreadableAnnotationDataError(`a colour "${text.slice(0, 32)}" is not #RRGGBB`);
  return [match[1], match[2], match[3]].map((hex) => Number.parseInt(hex ?? '0', 16) / 255);
}

/**
 * One XFDF element as a candidate record — or none, for an element this build does not exchange
 * (a `<fileattachment>`, a `<sound>`), which a foreign file may carry beside the ones it does.
 */
function xfdfCandidate(element: XfdfAnnotation): unknown[] {
  const subtype = SUBTYPE_OF_ELEMENT.get(element.element);
  if (subtype === undefined) return [];
  const get = (name: string): string | undefined => element.attributes.get(name);
  const candidate: Candidate = {
    page: Number(get('page')),
    subtype,
    rect: numbersOf(get('rect') ?? '', 'rect'),
  };
  const colourText = get('color');
  if (colourText !== undefined) candidate.colour = colourOf(colourText);
  const interior = get('interior-color');
  if (interior !== undefined) candidate.interiorColour = colourOf(interior);
  const opacity = get('opacity');
  if (opacity !== undefined) candidate.opacity = Number(opacity);
  const width = get('width');
  if (width !== undefined) candidate.borderWidth = Number(width);
  if (element.contents !== undefined) candidate.contents = element.contents;
  const title = get('title');
  if (title !== undefined) candidate.author = title;
  const subject = get('subject');
  if (subject !== undefined) candidate.subject = subject;
  const date = get('date');
  if (date !== undefined) candidate.modified = date;
  const icon = get('icon');
  if (icon !== undefined) candidate.icon = icon;
  const coords = get('coords');
  if (coords !== undefined) candidate.quadPoints = numbersOf(coords, 'coords');
  const vertices = get('vertices');
  if (vertices !== undefined) candidate.vertices = numbersOf(vertices, 'vertices');
  const start = get('start');
  const end = get('end');
  if (start !== undefined && end !== undefined) {
    candidate.line = [...numbersOf(start, 'start'), ...numbersOf(end, 'end')];
  }
  const head = get('head');
  const tail = get('tail');
  if (head !== undefined || tail !== undefined) candidate.lineEndings = [head ?? 'None', tail ?? 'None'];
  if (element.gestures.length > 0) {
    candidate.inkList = element.gestures.map((gesture) => numbersOf(gesture, 'a gesture'));
  }
  if (element.defaultAppearance !== undefined) candidate.defaultAppearance = element.defaultAppearance;
  return [candidate];
}

/**
 * An FDF's `/Annots`, read by the same entry reader the document walk uses.
 *
 * MuPDF declares no FDF API, so the bytes open as a document under the FDF type — `parseFormData`'s
 * route. `/Page` is the FDF's own entry; a dictionary without one is refused, because guessing a
 * page would put a note somewhere its author did not.
 */
function parseFdf(bytes: Uint8Array): readonly InterchangeAnnotation[] {
  let document: mupdf.Document;
  try {
    document = mupdf.PDFDocument.openDocument(bytes, 'application/vnd.fdf');
  } catch (error) {
    throw new UnreadableAnnotationDataError(error instanceof Error ? error.message : String(error));
  }
  if (!(document instanceof mupdf.PDFDocument)) {
    throw new UnreadableAnnotationDataError('it opened as something that is not PDF syntax');
  }
  try {
    const list = document.getTrailer().get('Root').get('FDF').get('Annots');
    if (!list.isArray()) throw new UnreadableAnnotationDataError('it has no /Root /FDF /Annots array');
    if (list.length > MAX_INTERCHANGE_ANNOTATIONS) {
      throw new UnreadableAnnotationDataError(`it carries more than ${String(MAX_INTERCHANGE_ANNOTATIONS)} annotations`);
    }
    const found: InterchangeAnnotation[] = [];
    for (let index = 0; index < list.length; index += 1) {
      const entry = list.get(index);
      if (!entry.isDictionary()) continue;
      const subtype = nameIn(entry.get('Subtype'));
      if (subtype === undefined || !(INTERCHANGE_SUBTYPES as readonly string[]).includes(subtype)) continue;
      const page = numberIn(entry.get('Page'));
      if (page === undefined) {
        throw new UnreadableAnnotationDataError(`annotation ${String(index + 1)} names no /Page`);
      }
      found.push(checked(candidateFrom(entry, page), index));
    }
    return found;
  } finally {
    document.destroy();
  }
}

/* ------------------------------------------------------------------- apply */

/**
 * Adds every annotation the file carries, or none.
 *
 * Every record is parsed and every page checked before the first is created, so a file naming a
 * page this document lacks changes nothing. Each annotation is created by MuPDF for its subtype,
 * given its entries raw in user space, marked as this build's, and drawn by `update()`.
 */
export const applyImportAnnotations: Apply<'mupdf', 'importAnnotations'> = (session, command) =>
  withDocument(session, (document) => {
    const records = parseAnnotationData(command.bytes, command.format);
    if (records.length === 0) throw new NoImportableAnnotationsError();
    const pages = document.countPages();
    for (const record of records) {
      if (record.page >= pages) throw new AnnotationPageMissingError(record.page, pages);
    }
    for (const record of records) {
      const annotation = document.loadPage(record.page).createAnnotation(record.subtype);
      writeEntries(document, annotation.getObject(), record);
      markAuthored(annotation);
      // DRAWN NOW, and not load-bearing for the file: measured 2026-09-17, with this call removed
      // MuPDF's save still wrote a correct appearance (`7 w`, `1 0 0 RG`, the inset box) for an
      // imported square. It is MuPDF's own call for an annotation whose entries changed, and it
      // gives the session an appearance before any save does.
      annotation.update();
    }
  });

function realArray(document: PDFDocument, numbers: readonly number[]): PDFObject {
  const array = document.newArray();
  for (const value of numbers) array.push(document.newReal(value));
  return array;
}

/**
 * The record's entries, onto a dictionary MuPDF just created. Every entry the record lacks is left
 * as MuPDF made it, so an imported square with no colour takes the engine's default rather than
 * an invisible one.
 */
function writeEntries(document: PDFDocument, dictionary: PDFObject, record: InterchangeAnnotation): void {
  dictionary.put('Rect', realArray(document, record.rect));
  if (record.colour !== undefined) dictionary.put('C', realArray(document, record.colour));
  if (record.interiorColour !== undefined) dictionary.put('IC', realArray(document, record.interiorColour));
  if (record.opacity !== undefined) dictionary.put('CA', document.newReal(record.opacity));
  if (record.borderWidth !== undefined) {
    const style = document.newDictionary();
    style.put('W', document.newReal(record.borderWidth));
    dictionary.put('BS', style);
  }
  if (record.contents !== undefined) dictionary.put('Contents', document.newString(record.contents));
  if (record.author !== undefined) dictionary.put('T', document.newString(record.author));
  if (record.subject !== undefined) dictionary.put('Subj', document.newString(record.subject));
  if (record.modified !== undefined) dictionary.put('M', document.newString(record.modified));
  if (record.quadPoints !== undefined) dictionary.put('QuadPoints', realArray(document, record.quadPoints));
  if (record.inkList !== undefined) {
    const strokes = document.newArray();
    for (const stroke of record.inkList) strokes.push(realArray(document, stroke));
    dictionary.put('InkList', strokes);
  }
  if (record.vertices !== undefined) dictionary.put('Vertices', realArray(document, record.vertices));
  if (record.line !== undefined) dictionary.put('L', realArray(document, record.line));
  if (record.lineEndings !== undefined) {
    const endings = document.newArray();
    for (const ending of record.lineEndings) endings.push(document.newName(ending));
    dictionary.put('LE', endings);
  }
  if (record.icon !== undefined) dictionary.put('Name', document.newName(record.icon));
  if (record.defaultAppearance !== undefined) dictionary.put('DA', document.newString(record.defaultAppearance));
}

/**
 * An import records no prior state, for `captureImportFormData`'s reason: what it adds is decided
 * by a file the command has not parsed yet, and the checkpoint restores the document exactly.
 */
export function captureImportAnnotations(): Promise<CaptureResult<never>> {
  return Promise.resolve({
    captured: false,
    reason:
      'an import adds whatever annotations the file carries, which the command cannot know before ' +
      'it parses — the checkpoint restores the document exactly',
  });
}

/** Unreachable, and required by `CommandSpec`'s shape — `invertImportFormData`'s reason. */
export const invertImportAnnotations: Invert<'mupdf', 'importAnnotations'> = (): Promise<void> => {
  throw new Error('imported annotations have no inverse; undo restores the checkpoint the bus took (ADR-0037)');
};
